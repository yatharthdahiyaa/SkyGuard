/**
 * Formats compact MQTT JSON telemetry payload according to SkyGuard Edge Schema.
 * Uses stack-safe snprintf with zero heap allocation.
 */
static inline int edge_serialize_json_payload(
    const char* station_id,
    const char* timestamp_iso,
    const SensorRawReading* r,
    const EdgeAnalysisResult* edge,
    const EdgeDiagInfo* diag,
    char* out_buf,
    size_t max_buf_len
) {
    if (!station_id || !timestamp_iso || !r || !edge || !diag || !out_buf || max_buf_len == 0) {
        return -1;
    }

    return snprintf(
        out_buf,
        max_buf_len,
        "{\"sid\":\"%s\",\"ts\":\"%s\",\"raw\":{\"T\":%.2f,\"P\":%.2f,\"RH\":%.2f},\"edge\":{\"flag\":%u,\"desc\":\"%s\",\"td\":%.2f,\"t_step\":%.2f,\"p_step\":%.2f,\"rh_step\":%.2f},\"diag\":{\"vbat\":%.2f,\"rssi\":%d,\"spool_len\":%u}}",
        station_id,
        timestamp_iso,
        r->T,
        r->P,
        r->RH,
        (unsigned int)edge->flag,
        edge->desc,
        edge->td,
        edge->t_step,
        edge->p_step,
        edge->rh_step,
        diag->vbat,
        (int)diag->rssi,
        (unsigned int)diag->spool_len
    );
}

/**
 * Circular Spool Storage: Flash/SPIFFS persistent storage simulation.
 */
static inline void spool_storage_init(CircularSpoolStorage* spool) {
    if (!spool) return;
    spool->head = 0;
    spool->tail = 0;
    spool->count = 0;
    spool->total_dropped_overflow = 0;
    memset(spool->queue, 0, sizeof(spool->queue));
}

/**
 * Enqueue payload during network blackout.
 * Overwrites oldest if capacity reached to preserve the most recent telemetry.
 */
static inline bool spool_storage_push(CircularSpoolStorage* spool, const char* json_payload) {
    if (!spool || !json_payload) return false;

    if (spool->count >= EDGE_MAX_SPOOL_RECORDS) {
        // Queue full: overwrite oldest (circular FIFO drop)
        spool->tail = (spool->tail + 1) % EDGE_MAX_SPOOL_RECORDS;
        spool->total_dropped_overflow++;
    } else {
        spool->count++;
    }

    strncpy(spool->queue[spool->head].payload, json_payload, EDGE_MAX_PAYLOAD_SIZE - 1);
    spool->queue[spool->head].payload[EDGE_MAX_PAYLOAD_SIZE - 1] = '\0';
    spool->head = (spool->head + 1) % EDGE_MAX_SPOOL_RECORDS;

    return true;
}

/**
 * Pop oldest payload when network reconnects (FIFO drain).
 */
static inline bool spool_storage_pop(CircularSpoolStorage* spool, char* out_payload, size_t max_len) {
    if (!spool || !out_payload || spool->count == 0) return false;

    strncpy(out_payload, spool->queue[spool->tail].payload, max_len - 1);
    out_payload[max_len - 1] = '\0';

    spool->tail = (spool->tail + 1) % EDGE_MAX_SPOOL_RECORDS;
    spool->count--;

    return true;
}

static inline uint16_t spool_storage_get_count(const CircularSpoolStorage* spool) {
    return spool ? spool->count : 0;
}

